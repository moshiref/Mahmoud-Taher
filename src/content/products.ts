/**
 * Width descriptors are the real file widths (small sources are never
 * upscaled, so two sizes can be the same file — listed once).
 */
export const srcSet = (image: ProductImage) => {
  const seen = new Set<number>()
  return ([1200, 2000, 3200] as const)
    .map((size) => [image.src[size], Math.round(image.width * Math.min(1, size / Math.max(image.width, image.height)))] as const)
    .filter(([, w]) => !seen.has(w) && seen.add(w))
    .map(([src, w]) => `${src} ${w}w`)
    .join(', ')
}
