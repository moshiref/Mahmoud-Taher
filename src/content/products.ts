/**
 * ─────────────────────────────────────────────────────────────
 *  PRODUCTS — collections shown at /products and /products/<slug>.
 *
 *  To add a collection's work:
 *   1. python scripts/optimize_product_images.py <slug> <image1> <image2> …
 *      (writes web versions to public/products/<slug>/ and prints sizes)
 *   2. Add one `item(...)` per image to that collection below.
 *  Empty collections render an elegant "in preparation" state.
 *  Titles are descriptive captions — edit freely.
 * ─────────────────────────────────────────────────────────────
 */

export interface ProductImage {
  id: string
  title: string
  alt: string
  /** Source dimensions — used for the exact aspect ratio (never cropped). */
  width: number
  height: number
  /** Long-edge widths generated by the optimisation script. */
  src: { 1200: string; 2000: string; 3200: string }
}

export interface ProductCollection {
  slug: string
  title: string
  items: ProductImage[]
  /** Show a caption under each image (and its title in the viewer). Default true. */
  captions?: boolean
}

const item = (slug: string, n: number, title: string, alt: string, width: number, height: number): ProductImage => {
  const base = `/products/${slug}/${slug}-${String(n).padStart(2, '0')}`
  return {
    id: `${slug}-${n}`,
    title,
    alt,
    width,
    height,
    src: { 1200: `${base}-1200.webp`, 2000: `${base}-2000.webp`, 3200: `${base}-3200.webp` },
  }
}

